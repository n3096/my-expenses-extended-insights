    static async init() {
        this.updateDOM();
        window.addEventListener('i18n-update-required', () => this.updateDOM());
    }

    static get(key) {
        const lang = AppStore.state.ui.currentLang || 'de';
        const pack = this.translations[lang] || this.translations['de'];
        return pack[key] || key;
    }

    static updateDOM() {
        const elements = document.querySelectorAll('[data-i18n-key]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n-key');
            const translation = this.get(key);
            if (el.tagName === 'INPUT' && el.placeholder) {
                el.placeholder = translation;
            } else {
                el.textContent = translation;
            }
        });
    }

    static formatCurrency(amount, currency) {
        const lang = AppStore.state.ui.currentLang || 'de';
        const locale = lang === 'ja' ? 'ja-JP' : (lang === 'en' ? 'en-US' : 'de-DE');
        return new Intl.NumberFormat(locale, { style: 'currency', currency: currency }).format(amount);
    }
